import re

import numpy as np

from lighteval.metrics.metrics_sample import SampleLevelComputation
from lighteval.metrics.utils.metric_utils import SampleLevelMetric
from lighteval.tasks.lighteval_task import LightevalTaskConfig
from lighteval.tasks.requests import Doc, SamplingMethod


RELEASES = ("2024b", "2025a", "2026a")
DOMAINS = (
    ("cs", "cs"),
    ("q_fin", "q-fin"),
    ("math", "math"),
    ("physics", "physics"),
    ("stat", "stat"),
    ("q_bio", "q-bio"),
    ("econ", "econ"),
    ("eess", "eess"),
)
TASK_TYPES = ("s", "c", "p")


class ArxivRollBenchExactMatch(SampleLevelComputation):
    def compute(self, doc: Doc, model_response, **kwargs) -> float:
        task_type = (doc.specific or {}).get("task_type")
        golds = {self._extract_answer(gold, task_type) for gold in doc.get_golds()}
        responses = model_response.text_post_processed or model_response.text or []
        preds = [self._extract_answer(pred, task_type) for pred in responses]
        return float(any(pred in golds for pred in preds if pred is not None))

    @staticmethod
    def _extract_answer(text: str, task_type: str) -> str | None:
        if text is None:
            return None

        if task_type in {"s", "c"}:
            match = re.search(r"\bSelection\s*([1-4])\b", text, flags=re.IGNORECASE)
            return f"Selection {match.group(1)}" if match else None

        if task_type == "p":
            match = re.search(r"\b([ABCD])\b", text, flags=re.IGNORECASE)
            return match.group(1).upper() if match else None

        return None


ARXIVROLLBENCH_EXACT_MATCH = SampleLevelMetric(
    metric_name="em",
    sample_level_fn=ArxivRollBenchExactMatch(),
    category=SamplingMethod.GENERATIVE,
    corpus_level_fn=np.mean,
    higher_is_better=True,
)


def arxivrollbench_prompt(line, task_name: str = None):
    task_type = task_name.rsplit(":", 1)[-1]

    if task_type in {"s", "c"}:
        task_label = "sequencing" if task_type == "s" else "cloze"
        choices = ["Selection 1", "Selection 2", "Selection 3", "Selection 4"]
        query = (
            f"ArxivRollBench {task_label} task.\n"
            "Select the correct ordering from the four options below. "
            "Answer only with Selection 1, Selection 2, Selection 3, or Selection 4.\n\n"
            f"{line['shuffled_text']}\n\n"
            f"Selection 1: {line['A']}\n"
            f"Selection 2: {line['B']}\n"
            f"Selection 3: {line['C']}\n"
            f"Selection 4: {line['D']}\n\n"
            "Answer:"
        )
    elif task_type == "p":
        choices = ["A", "B", "C", "D"]
        query = (
            "ArxivRollBench prediction task.\n"
            "Select the most plausible next sentence from the four options below. "
            "Answer only with A, B, C, or D.\n\n"
            f"Context:\n{line['context']}\n\n"
            f"A. {line['A']}\n"
            f"B. {line['B']}\n"
            f"C. {line['C']}\n"
            f"D. {line['D']}\n\n"
            "Answer:"
        )
    else:
        raise ValueError(f"Unsupported ArxivRollBench task type: {task_type}")

    return Doc(
        task_name=task_name,
        query=query,
        choices=choices,
        gold_index=choices.index(line["label"]),
        specific={"task_type": task_type},
    )


def _dataset_path(release: str, hf_domain: str, task_type: str, compact: bool) -> str:
    if release == "2024b":
        path = f"liangzid/robench2024b_all_set{hf_domain}SCP-{task_type}"
    else:
        path = f"liangzid/robench{release}_test_all_category_set{hf_domain}SCP-{task_type}"

    return f"{path}-50" if compact else path


def _make_task(name: str, release: str, hf_domain: str, task_type: str, compact: bool) -> LightevalTaskConfig:
    return LightevalTaskConfig(
        name=name,
        prompt_function=arxivrollbench_prompt,
        hf_repo=_dataset_path(release, hf_domain, task_type, compact),
        hf_subset="default",
        hf_avail_splits=["train"],
        evaluation_splits=["train"],
        few_shots_split=None,
        few_shots_select=None,
        generation_size=50,
        metrics=[ARXIVROLLBENCH_EXACT_MATCH],
        stop_sequence=[".", ",", "\n"],
        version=0,
    )


TASKS_TABLE = []

for release in RELEASES:
    for domain, hf_domain in DOMAINS:
        for task_type in TASK_TYPES:
            TASKS_TABLE.extend(
                [
                    _make_task(
                        f"arxivrollbench:{release}:{domain}:{task_type}",
                        release,
                        hf_domain,
                        task_type,
                        compact=True,
                    ),
                    _make_task(
                        f"arxivrollbench{release}:{domain}:{task_type}",
                        release,
                        hf_domain,
                        task_type,
                        compact=True,
                    ),
                    _make_task(
                        f"arxivrollbench_full:{release}:{domain}:{task_type}",
                        release,
                        hf_domain,
                        task_type,
                        compact=False,
                    ),
                    _make_task(
                        f"arxivrollbench{release}_full:{domain}:{task_type}",
                        release,
                        hf_domain,
                        task_type,
                        compact=False,
                    ),
                ]
            )
